# 8 誤解六
slide("""
<div class="myth"><span class="no">誤解 6</span>誤想防衛者沒有故意，所以教唆、幫助他的人也不罰</div>
<div class="truth"><span class="yes">正解</span>依<b>限制法律效果之罪責理論</b>，構成要件故意<b>仍然存在</b>，主行為是「故意不法行為」。</div>
<ul>
  <li>限制從屬性：共犯只需從屬於正犯的<b>故意、不法</b>行為</li>
  <li>→ 明知真相、卻利用他人誤會而<b>教唆、幫助</b>者，仍可成立共犯</li>
  <li>若誤會是由幕後者一手製造，另須檢討<b>間接正犯</b></li>
  <li>這也是多數說捨「阻卻構成要件故意」而採此說的重要理由</li>
</ul>
""",
"誤解六：誤想防衛的人沒有故意，所以教唆或幫助他的人，也都不罰。",
"這要看採哪一說。依限制法律效果之罪責理論，構成要件故意仍然存在，正犯的行為還是故意的不法行為。",
"在限制從屬性之下，共犯只需要從屬於正犯故意、不法的行為。所以，明知真相、卻利用別人誤會去教唆或幫助的人，仍然可以成立共犯。",
"這正是多數說不採阻卻構成要件故意，而採限制法律效果之罪責理論的重要理由。")

